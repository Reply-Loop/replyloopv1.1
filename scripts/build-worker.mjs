#!/usr/bin/env node
/**
 * Packs the static export (out/) into a self-contained Cloudflare Worker in
 * worker/, deployable with `wrangler deploy -c worker/wrangler.toml`
 * (npm run deploy:worker).
 *
 * Why a Worker and not Pages: Pages (and Workers static assets) upload files
 * with a short-lived upload token in the Authorization header. In a sandbox
 * whose proxy injects its own Cloudflare credential into that header, those
 * uploads are refused. A Worker script upload uses the account credential
 * only, so every file is bundled into the script as a binary module instead.
 *
 * The router mirrors what Pages does for this site: clean URLs (/about serves
 * about.html, /about/ and /about.html redirect to /about), 404.html with a 404
 * status, the rules from out/_headers, HEAD, and byte ranges (Safari needs
 * them to play the film).
 */
import { cpSync, mkdirSync, renameSync, readFileSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = join(root, "out");
const dir = join(root, "worker");
mkdirSync(dir, { recursive: true });
// A copy under worker/site (renamed to *.bin below) for the bundle.
rmSync(join(dir, "site"), { recursive: true, force: true });
cpSync(out, join(dir, "site"), { recursive: true });

const walk = (d) =>
  readdirSync(d).flatMap((n) => {
    const p = join(d, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });

const files = walk(out)
  .map((p) => "/" + relative(out, p).split("\\").join("/"))
  .filter((p) => p !== "/_headers")
  .sort();

// _headers -> [{ pattern, headers }], in file order (Pages applies every match).
const headerRules = [];
let current = null;
for (const line of readFileSync(join(out, "_headers"), "utf8").split("\n")) {
  if (!line.trim()) continue;
  if (!/^\s/.test(line)) {
    current = { pattern: line.trim(), headers: {} };
    headerRules.push(current);
  } else if (current) {
    const i = line.indexOf(":");
    current.headers[line.slice(0, i).trim()] = line.slice(i + 1).trim();
  }
}

// Every file gets a .bin suffix inside the bundle, which wrangler's built-in
// rule loads as binary Data (an ArrayBuffer). URL paths stay the same.
const bundled = (f) => f + ".bin";
for (const f of files) if (bundled(f) !== f) renameSync(join(dir, "site", f), join(dir, "site", bundled(f)));

const imports = files.map((f, i) => `import f${i} from ${JSON.stringify("./site" + bundled(f))};`).join("\n");
const table = files.map((f, i) => `  [${JSON.stringify(f)}, f${i}],`).join("\n");
writeFileSync(
  join(dir, "files.generated.js"),
  `// GENERATED by scripts/build-worker.mjs from out/. Do not edit.\n${imports}\n\nexport const FILES = new Map([\n${table}\n]);\n\nexport const HEADER_RULES = ${JSON.stringify(headerRules, null, 2)};\n`,
);

writeFileSync(
  join(dir, "wrangler.toml"),
  `# GENERATED by scripts/build-worker.mjs. Deploy: npm run deploy:worker
name = "reply-loop-website"
main = "index.js"
compatibility_date = "2026-11-01"
workers_dev = true
`,
);

const total = files.reduce((n, f) => n + statSync(join(out, f)).size, 0);
console.log(`worker/: ${files.length} files (${(total / 1048576).toFixed(2)} MB raw), ${headerRules.length} header rules`);
