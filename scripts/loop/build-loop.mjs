#!/usr/bin/env node
/**
 * Turns assets/loop/loop-fit.json into src/lib/loop/geometry.generated.ts:
 * SVG paths for the flat mark (logo B) and the thread, plus the point list
 * the 3D loop and the brand film sweep along.
 *
 * Run: node scripts/loop/build-loop.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const fit = JSON.parse(readFileSync(join(root, "assets/loop/loop-fit.json"), "utf8"));
const pts = fit.points; // 256 points, half-width 1, y up, s=0 at the crossing on the rising strand
const N = pts.length;

// SVG space: half-width 100, y down.
const S = 100;
const toSvg = ([x, y]) => [x * S, -y * S];
const r = (v) => Math.round(v * 100) / 100;

/** Closed Catmull-Rom spline through every `step`-th point, as cubic Beziers. */
function closedPath(step) {
  const p = pts.filter((_, i) => i % step === 0).map(toSvg);
  const n = p.length;
  let d = `M${r(p[0][0])} ${r(p[0][1])}`;
  for (let i = 0; i < n; i++) {
    const p0 = p[(i - 1 + n) % n], p1 = p[i], p2 = p[(i + 1) % n], p3 = p[(i + 2) % n];
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += `C${r(c1[0])} ${r(c1[1])} ${r(c2[0])} ${r(c2[1])} ${r(p2[0])} ${r(p2[1])}`;
  }
  return `${d}Z`;
}

/** Open Catmull-Rom path over the arc s in [from, to] (fractions of the length). */
function arcPath(from, to) {
  const idx = [];
  for (let i = Math.round(from * N); i <= Math.round(to * N); i++) idx.push(((i % N) + N) % N);
  const p = idx.map((i) => toSvg(pts[i]));
  const at = (i) => p[Math.max(0, Math.min(p.length - 1, i))];
  let d = `M${r(p[0][0])} ${r(p[0][1])}`;
  for (let i = 0; i < p.length - 1; i++) {
    const p0 = at(i - 1), p1 = at(i), p2 = at(i + 1), p3 = at(i + 2);
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += `C${r(c1[0])} ${r(c1[1])} ${r(c2[0])} ${r(c2[1])} ${r(p2[0])} ${r(p2[1])}`;
  }
  return d;
}

const stroke = fit.strokeOverHalfWidth * S;
// The kit's ivory span is [-0.070, 0.055]; centred to +/-0.0625 (same 12.5% length) for a symmetric mark.
const IVORY = 0.0625;
const ys = pts.map(([, y]) => Math.abs(y));
const halfH = Math.max(...ys) * S;
const padX = S + stroke / 2 + 2, padY = halfH + stroke / 2 + 2;
const viewBox = `${r(-padX)} ${r(-padY)} ${r(padX * 2)} ${r(padY * 2)}`;

const out = `/**
 * GENERATED by scripts/loop/build-loop.mjs from assets/loop/loop-fit.json. Do not edit.
 * Source: ${fit.source}. Fit error: median ${fit.fitErrorPx?.median ?? "?"} px.
 */

/** viewBox for the flat mark: half-width 100, centred on the crossing, y down. */
export const LOOP_VIEWBOX = "${viewBox}";
export const LOOP_ASPECT = ${r((padX * 2) / (padY * 2))};
/** Stroke width in viewBox units (kit: ~8% of the mark's width). */
export const LOOP_STROKE = ${r(stroke)};
/** The whole figure-eight, one closed path. Starts at the crossing on the rising strand. */
export const LOOP_PATH = "${closedPath(4)}";
/** The crossing detail: the rising strand over the crossing, 12.5% of the length. */
export const LOOP_CROSSING_PATH = "${arcPath(-IVORY, IVORY)}";
export const LOOP_CROSSING_RANGE = [${-IVORY}, ${IVORY}] as const;
/** 128 points along the curve (half-width 1, y up), for the 3D tube and the film. */
export const LOOP_POINTS: ReadonlyArray<readonly [number, number]> = ${JSON.stringify(pts.filter((_, i) => i % 2 === 0))};
`;
writeFileSync(join(root, "src/lib/loop/geometry.generated.ts"), out);

// Favicon: the kit avatar treatment (brass loop, ivory crossing, charcoal field).
const k = 54 / (padX * 2); // mark spans 54 of 64 px
const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="14" fill="#1B1F23"/><g transform="translate(32 32) scale(${r(k * 1000) / 1000})" fill="none"><path d="${closedPath(4)}" stroke="#8A5F1C" stroke-width="${r(stroke)}" stroke-linejoin="round"/><path d="${arcPath(-IVORY, IVORY)}" stroke="#F8F5EF" stroke-width="${r(stroke + 0.4)}"/></g></svg>\n`;
writeFileSync(join(root, "src/app/icon.svg"), icon);
console.log(`wrote src/lib/loop/geometry.generated.ts (viewBox ${viewBox}, stroke ${r(stroke)})`);
